/* ---------- Frete por região (CEP → valor e prazo) ----------
   Faixa inicial do CEP: 0-3 Sudeste | 4-5 Sul | 6 Nordeste (BA/SE)
   7 Centro-Oeste (GO/DF/TO) | 8-9 Norte e Nordeste (MA..AL / PA..RO) */
function calcularFrete(cep, opcoes = {}) {
  const d = Number(String(cep).replace(/\D/g, "").charAt(0)) || 0;
  let r;
  if (d <= 3) r = { valor: 19.9, prazo: "3 a 7 dias úteis", prazoExpresso: "1 a 2 dias úteis", regiao: "Sudeste" };
  else if (d <= 5) r = { valor: 23.9, prazo: "4 a 9 dias úteis", prazoExpresso: "1 a 3 dias úteis", regiao: "Sul" };
  else if (d === 6) r = { valor: 26.9, prazo: "6 a 12 dias úteis", prazoExpresso: "2 a 4 dias úteis", regiao: "Nordeste" };
  else if (d === 7) r = { valor: 18.9, prazo: "2 a 6 dias úteis", prazoExpresso: "1 a 2 dias úteis", regiao: "Centro-Oeste" };
  else r = { valor: 29.9, prazo: "8 a 15 dias úteis", prazoExpresso: "3 a 6 dias úteis", regiao: "Norte e Nordeste" };
  // Frete grátis somente com o cupom FRETEGRATIS (regra divulgada no site).
  r.gratis = !!opcoes.cupomFreteGratis;
  if (r.gratis) r.valor = 0;
  return r;
}

