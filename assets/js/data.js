/* ---------- Normalização dos produtos ----------
   Converte os campos para o formato usado pelos scripts:
   categoria (nome → id), estoque (boolean → número),
   detalhes (objeto → lista), marca nula → "HiT". */
const MAPA_CATEGORIAS = {
  "Tênis": "tenis",
  "Chinelos": "chinelos",
  "Camisetas": "camisetas",
  "Calças e bermudas": "calcas",
  "Jaquetas e moletons": "jaquetas",
};

PRODUTOS.forEach(p => {
  p.categoria = MAPA_CATEGORIAS[p.categoria] || p.categoria;
  if (!p.marca) p.marca = "HiT";
  if (typeof p.estoque !== "number") p.estoque = p.estoque ? 10 : 0;
  if (p.detalhes && !Array.isArray(p.detalhes))
    p.detalhes = Object.entries(p.detalhes).map(([k, v]) => `${k}: ${v}`);
  if (!Array.isArray(p.tags)) p.tags = [];
  if (!Array.isArray(p.imagens)) p.imagens = [];
  if (!Array.isArray(p.tamanhos)) p.tamanhos = [];
  if (!Array.isArray(p.esgotados)) p.esgotados = [];
  if (!Array.isArray(p.cores)) p.cores = [];
  if (!p.precoAntigo) p.precoAntigo = null;
  p.promo = !!p.promo;
  p.novidade = !!p.novidade;
  p.destaque = !!p.destaque;
});
